// Writes vectors.json: fixed inputs -> every intermediate byte string of a
// vault write and read, for checking a Dart or Swift port. Nothing touches the
// network. Each write vector is built twice, once by vault.mjs (hand-rolled,
// the thing a port copies) and once by the official @arkiv-network/sdk through
// a transport that captures the signed transaction instead of sending it, and
// the two must be identical byte for byte.
//   node vectors.mjs          (writes vectors.json, exits 1 on any mismatch)
import fs from 'node:fs';
import { bytesToHex, defineChain, hexToBytes, keccak256, custom, serializeTransaction, parseTransaction, decodeFunctionData } from 'viem';
import { privateKeyToAccount } from 'viem/accounts';
import { createWalletClient, ExpirationTime } from '@arkiv-network/sdk';
import { bytes, defineSchema, key, u64 } from '@arkiv-network/sdk/schema';
import * as V from './vault.mjs';

// ------------------------------------------------------------ fixed inputs
const SECRET = hexToBytes('0x000102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f');
const ITEM = { id: 'field:addr-home', type: 'field', kind: 'address', label: 'Home', value: '1 Infinite Loop, Cupertino, CA 95014', updatedAt: 1793900000000 };
const ITEM_EDITED = { ...ITEM, value: '1 Apple Park Way, Cupertino, CA 95014', updatedAt: 1793900600000 };
const NONCE_1 = hexToBytes('0x0a0b0c0d0e0f101112131415');
const NONCE_2 = hexToBytes('0x1a1b1c1d1e1f202122232425');
const SALT = 0x0123456789abcdef0123456789abcdefn;
const ENTITY_NONCE = 0n; // owner's entityNonce before the create
const CURRENT_BLOCK = 263000n;
const TX = { gas: 500000n, maxFeePerGas: 2_000_000_000n, maxPriorityFeePerGas: 1_000_000n };

const keys = V.deriveKeys(SECRET);
const account = privateKeyToAccount(keys.ownerKey);
const out = { about: 'Glyf Vault on Arkiv (Rabdi, chain 7794095) test vectors. See PROTOCOL.md and DESIGN.md. Generated by vectors.mjs; every write was also built by @arkiv-network/sdk 1.0.1 and matched byte for byte.', inputs: {}, keys: {}, item: {}, writes: {}, reads: {} };

out.inputs = {
  vaultSecret: bytesToHex(SECRET), item: ITEM, itemEdited: ITEM_EDITED,
  aesNonce1: bytesToHex(NONCE_1), aesNonce2: bytesToHex(NONCE_2), salt: '0x' + SALT.toString(16).padStart(32, '0'),
  entityNonceBeforeCreate: ENTITY_NONCE.toString(), currentBlock: CURRENT_BLOCK.toString(),
  tx: { chainId: V.ARKIV.chainId, type: 'eip1559', gas: TX.gas.toString(), maxFeePerGas: TX.maxFeePerGas.toString(), maxPriorityFeePerGas: TX.maxPriorityFeePerGas.toString(), to: V.ARKIV.address, value: '0', nonces: { create: 0, patch: 1, extend: 2, delete: 3 } },
};
out.keys = {
  hkdf: 'HKDF-SHA256, salt = UTF-8 "glyf-vault-hkdf-v1", L = 32',
  ownerKeyInfo: 'UTF-8 "glyf/vault/v1/arkiv-owner" || one counter byte (0x00 first; next if the result is 0 or >= n)',
  ownerPrivateKey: keys.ownerKey, ownerAddress: keys.owner,
  aesKeyInfo: 'UTF-8 "glyf/vault/v1/aes-256-gcm"', aesKey: bytesToHex(keys.aesKey),
  itemKeyInfo: 'UTF-8 "glyf/vault/v1/item-id"', itemKey: bytesToHex(keys.itemKey),
};

// ------------------------------------------------------------ item crypto
const h = V.itemHash(keys, ITEM.id);
const enc1 = V.encryptItem(keys, ITEM, { nonce: NONCE_1 });
const enc2 = V.encryptItem(keys, ITEM_EDITED, { nonce: NONCE_2 });
out.item = {
  itemHash: h,
  json: JSON.stringify(ITEM),
  paddedPlaintext: bytesToHex(V.pad(JSON.stringify(ITEM))),
  aad: bytesToHex(V.aad(V.ARKIV.chainId, keys.owner, h)),
  ct: enc1.ct,
  ctEdited: enc2.ct,
  ctLayout: '0x01 || nonce(12) || AES-256-GCM ciphertext(len = padded plaintext) || tag(16)',
};
const back = V.decryptItem(keys, h, enc1.ct);
if (JSON.stringify(back) !== JSON.stringify(ITEM)) throw new Error('decrypt round trip failed');

// ------------------------------------------------------- SDK capture client
const chain = defineChain({ id: V.ARKIV.chainId, name: 'Rabdi', nativeCurrency: { name: 'Golem', symbol: 'tGLM', decimals: 18 }, rpcUrls: { default: { http: [V.ARKIV.rpc] } } });
let captured;
const transport = custom({
  async request({ method, params }) {
    switch (method) {
      case 'eth_chainId': return '0x' + V.ARKIV.chainId.toString(16);
      case 'eth_blockNumber': return '0x' + CURRENT_BLOCK.toString(16);
      case 'eth_getBlockByNumber': return { number: '0x' + CURRENT_BLOCK.toString(16), baseFeePerGas: '0x3b9aca00', timestamp: '0x0', transactions: [] };
      case 'eth_sendRawTransaction': captured = params[0]; throw new Error('CAPTURED');
      default: throw new Error(`capture transport: unexpected ${method}`);
    }
  },
}, { retryCount: 0 });
const sdk = createWalletClient({ chain, transport, account });
const Vault = defineSchema(V.SCHEMA_TAG, { v: u64().indexed(), item: key().indexed(), ct: bytes() });
async function viaSdk(fn) {
  captured = undefined;
  try { await fn(); } catch (e) { if (!captured) throw e; }
  return captured;
}

const sign = (data, nonce) => account.signTransaction({ chainId: V.ARKIV.chainId, type: 'eip1559', to: V.ARKIV.address, value: 0n, data, nonce, ...TX });
let mismatches = 0;
async function vector(name, ops, nonce, sdkFn) {
  const calldata = V.executeCalldata(ops);
  const raw = await sign(calldata, nonce);
  const sdkRaw = await viaSdk(sdkFn);
  const same = sdkRaw === raw;
  if (!same) {
    mismatches++;
    const t = parseTransaction(sdkRaw);
    console.error(`MISMATCH ${name}\n ours ${calldata}\n sdk  ${t.data}`);
  }
  out.writes[name] = {
    operations: ops.map((o) => ({ operation: o.operation, operationData: o.operationData })),
    calldata,
    unsignedTx: serializeTransaction({ chainId: V.ARKIV.chainId, type: 'eip1559', to: V.ARKIV.address, value: 0n, data: calldata, nonce, ...TX }),
    rawSignedTx: raw,
    txHash: keccak256(raw),
    matchesSdk: same,
  };
}

// create
const attributes = V.vaultAttributes(enc1);
out.writes.note = 'execute(ops) on 0x4400000000000000000000000000000000000044, selector 0x49650044. Raw txs are EIP-1559 (type 2) signed by keys.ownerPrivateKey.';
out.writes.createAttributes = attributes;
await vector('create', [V.createOp({ salt: SALT, attributes })], 0, () =>
  sdk.createEntity(Vault, { v: u64(V.FORMAT_V), item: key(enc1.item), ct: bytes(enc1.ct) },
    { expiration: ExpirationTime.fromDays(V.LIFETIME_DAYS), flags: { permissionlessExtension: true }, salt: SALT },
    { nonce: 0, ...TX }));

const entityKey = V.predictEntityKey({ owner: keys.owner, nonce: ENTITY_NONCE, salt: SALT });
out.writes.predictedEntityKey = entityKey;
out.writes.entityNonceCall = { to: V.ARKIV.address, data: V.entityNonceCalldata(keys.owner) };

await vector('patch', [V.patchOp({ entityKey, mutations: V.vaultPatchMutations(enc2) })], 1, () =>
  sdk.patchEntity(Vault, entityKey, { set: { ct: bytes(enc2.ct), v: u64(V.FORMAT_V) } }, { nonce: 1, ...TX }));

await vector('extend', [V.extendOp({ entityKey })], 2, () =>
  sdk.extendEntity({ entityKey, expiration: ExpirationTime.fromDays(V.LIFETIME_DAYS) }, { nonce: 2, ...TX }));

await vector('delete', [V.deleteOp({ entityKey })], 3, () => sdk.deleteEntity({ entityKey }, { nonce: 3, ...TX }));

// a batch: create two items in one transaction (what a first backup does)
const item2 = { id: 'snippet:;mail', type: 'snippet', trigger: ';mail', text: 'arpit@example.com', updatedAt: 1793900000000 };
const enc3 = V.encryptItem(keys, item2, { nonce: NONCE_2 });
const salt2 = SALT + 1n;
await vector('batchCreate2', [V.createOp({ salt: SALT, attributes }), V.createOp({ salt: salt2, attributes: V.vaultAttributes(enc3) })], 0, () =>
  sdk.executeBatch({
    creates: [
      { schema: Vault, values: { v: u64(V.FORMAT_V), item: key(enc1.item), ct: bytes(enc1.ct) }, expiration: ExpirationTime.fromDays(V.LIFETIME_DAYS), flags: { permissionlessExtension: true }, salt: SALT },
      { schema: Vault, values: { v: u64(V.FORMAT_V), item: key(enc3.item), ct: bytes(enc3.ct) }, expiration: ExpirationTime.fromDays(V.LIFETIME_DAYS), flags: { permissionlessExtension: true }, salt: salt2 },
    ],
  }, { nonce: 0, ...TX }));
out.writes.batchCreate2.items = [ITEM.id, item2.id];
out.writes.batchCreate2.predictedKeys = [entityKey, V.predictEntityKey({ owner: keys.owner, nonce: ENTITY_NONCE + 1n, salt: salt2 })];

// sanity: the calldata decodes back to what we put in
const dec = decodeFunctionData({ abi: V.EXECUTE_ABI, data: out.writes.create.calldata });
if (dec.args[0][0].operation !== 1) throw new Error('decode failed');

// ------------------------------------------------------------------ reads
const [q, opts] = V.restoreQuery(keys.owner);
const [q2, opts2] = V.restoreQuery(keys.owner, entityKey);
const sampleEntity = {
  key: entityKey, owner: keys.owner, expiresAt: '0x' + (CURRENT_BLOCK + 1n + V.LIFETIME_BLOCKS).toString(16), updatedAt: '0x' + (CURRENT_BLOCK + 1n).toString(16),
  attributes: [
    { name: 'arkiv.schema', type: 'str', value: V.SCHEMA_TAG },
    { name: 'ct', type: 'bytes', value: enc1.ct },
    { name: 'item', type: 'key', value: enc1.item },
    { name: 'v', type: 'u64', value: '0x1' },
  ],
};
const parsed = V.readVaultEntity(sampleEntity);
out.reads = {
  restoreFirstPage: { jsonrpc: '2.0', id: 1, method: 'arkiv_query', params: [q, opts] },
  restoreNextPage: { jsonrpc: '2.0', id: 1, method: 'arkiv_query', params: [q2, opts2], note: 'afterKey = last key of the previous page; stop when a page has < 100 rows' },
  getEntity: { jsonrpc: '2.0', id: 1, method: 'arkiv_getEntity', params: [entityKey] },
  oneItem: { jsonrpc: '2.0', id: 1, method: 'arkiv_query', params: [`arkiv.schema = str('${V.SCHEMA_TAG}') AND $owner = addr(${keys.owner}) AND item = key(${h})`, { select: { key: true, expiresAt: true, attributes: true } }] },
  expiringSoon: { jsonrpc: '2.0', id: 1, method: 'arkiv_query', params: [`arkiv.schema = str('${V.SCHEMA_TAG}') AND $owner = addr(${keys.owner}) AND $expiresAt < u64(${CURRENT_BLOCK + V.RENEW_BELOW_BLOCKS})`, { select: { key: true, expiresAt: true } }] },
  sampleResultEntity: sampleEntity,
  sampleDecrypted: V.decryptItem(keys, parsed.item, parsed.ct),
};

fs.writeFileSync(new URL('./vectors.json', import.meta.url), JSON.stringify(out, (k, v) => (typeof v === 'bigint' ? v.toString() : v), 2) + '\n');
console.log(`vectors.json written; owner ${keys.owner}; ${Object.keys(out.writes).filter((k) => out.writes[k].rawSignedTx).length} write vectors, ${mismatches} mismatches with the SDK`);
process.exit(mismatches ? 1 : 0);
