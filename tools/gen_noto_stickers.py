#!/usr/bin/env python3
"""Writes the Noto Animated Emoji sticker catalogue into both keyboards.

The server's catalogue (server/src/registry/stickers/noto.json, most popular
first) becomes a source file on each phone, so the Stickers tab searches it
on the phone with no request (docs/SERVER-INVENTORY.md, 2026-10-14):

  app/ios/GlyfKeyboard/Engine/NotoCatalogue.generated.swift
  app/android/app/src/main/kotlin/com/arpit/glyf/ime/NotoCatalogue.kt

One line per sticker, in the catalogue's order: "codepoints|category|name,name".
Run again whenever noto.json changes:  python3 tools/gen_noto_stickers.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "server/src/registry/stickers/noto.json"
SWIFT = ROOT / "app/ios/GlyfKeyboard/Engine/NotoCatalogue.generated.swift"
KOTLIN = ROOT / "app/android/app/src/main/kotlin/com/arpit/glyf/ime/NotoCatalogue.kt"

stickers = json.loads(SOURCE.read_text(encoding="utf-8"))
lines = []
for s in stickers:
    parts = [s["c"], s["g"], *s["t"]]
    for p in parts:
        # The separators, and anything a Swift or Kotlin raw string would read.
        assert not any(ch in p for ch in '|,\n"\\$#'), p
    lines.append(f'{s["c"]}|{s["g"]}|{",".join(s["t"])}')
body = "\n".join(lines)

HEADER = ("Generated by tools/gen_noto_stickers.py from server/src/registry/stickers/noto.json;\n"
          "do not edit. Google's Noto Animated Emoji (CC BY 4.0), most popular first,\n"
          "skin-tone variants left out. One line per sticker: \"codepoints|category|name,name\".")

SWIFT.write_text(
    "// " + HEADER.replace("\n", "\n// ") + "\n\n"
    "enum NotoCatalogue {\n"
    f"    static let lines = #\"\"\"\n{body}\n\"\"\"#\n"
    "}\n",
    encoding="utf-8",
)

KOTLIN.write_text(
    "// " + HEADER.replace("\n", "\n// ") + "\n\n"
    "package com.arpit.glyf.ime\n\n"
    "internal object NotoCatalogue {\n"
    f"    const val LINES = \"\"\"{body}\"\"\"\n"
    "}\n",
    encoding="utf-8",
)
print(f"{len(stickers)} stickers -> {SWIFT.relative_to(ROOT)}, {KOTLIN.relative_to(ROOT)}")
